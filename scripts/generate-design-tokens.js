#!/usr/bin/env node
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const { compileTokenProfiles } = require('./lib/momentum-tokens');
const root = path.resolve(__dirname, '..');
const sourceText = fs.readFileSync(path.join(root, 'design/freed.mobile.tokens.json'), 'utf8');
const sourceHash = crypto.createHash('sha256').update(sourceText).digest('hex');
const compiled = compileTokenProfiles(JSON.parse(sourceText));
const tokenText = '// Generated by scripts/generate-design-tokens.js. Edit design/freed.mobile.tokens.json.\n' +
  `export const tokenSourceHash = ${JSON.stringify(sourceHash)} as const;\n` +
  `export const mobileTokens = ${JSON.stringify({ profiles: compiled.profiles }, null, 2)} as const;\n` +
  'export type MobileTokenProfile = keyof typeof mobileTokens.profiles;\nexport type MobileTokenPath = keyof typeof mobileTokens.profiles.base;\n';
const themeText = '// Generated by scripts/generate-design-tokens.js.\nimport { mobileTokens, type MobileTokenPath, type MobileTokenProfile } from "./tokens";\nexport interface MobileTheme { profile: MobileTokenProfile; values: Readonly<Record<MobileTokenPath, unknown>>; }\nexport function createMobileTheme(profile: MobileTokenProfile = "base"): MobileTheme { return { profile, values: mobileTokens.profiles[profile] }; }\n';
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const files = { 'tokens.ts': tokenText, 'theme.ts': themeText };
files['tokens.manifest.json'] = JSON.stringify({ format: 'mobile-native-token-manifest/1', source_hash: sourceHash,
  profiles: Object.keys(compiled.profiles), token_paths: compiled.paths,
  artifacts: Object.fromEntries(Object.entries(files).map(([key, value]) => [key, hash(value)])) }, null, 2) + '\n';
for (const [name, content] of Object.entries(files)) {
  const destination = path.join(root, 'src/design-system/generated', name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== content) throw new Error(`Stale design token artifact: ${name}`);
  } else fs.writeFileSync(destination, content);
}
console.log(`${compiled.paths.length} canonical design tokens ${process.argv.includes('--check') ? 'verified' : 'generated'} across ${Object.keys(compiled.profiles).length} profiles.`);
