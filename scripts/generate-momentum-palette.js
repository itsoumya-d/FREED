#!/usr/bin/env node
// Momentum's palette is authored once in the design-token document.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'design/freed.mobile.tokens.json'), 'utf8'));
const palettes = source.$extensions['org.freed.momentum'].palettes;
const output = '// Generated by scripts/generate-momentum-palette.js. Edit design/freed.mobile.tokens.json.\nexport const momentumPalettes = ' + JSON.stringify(palettes, null, 2) + ' as const;\n';
const target = path.join(root, 'src/design-system/generated/momentum-palette.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Momentum palette is stale. Run node scripts/generate-momentum-palette.js.');
} else fs.writeFileSync(target, output);
console.log('Momentum palette ' + (process.argv.includes('--check') ? 'verified' : 'generated') + ' from the canonical token document.');
