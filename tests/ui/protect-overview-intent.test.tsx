let mockDnsStatus:any={supported:false,releaseEnabled:false,configured:false,enabled:false,healthy:null,reason:null,provider:'cloudflare-families',requiresSettings:false};
jest.mock('@/hooks/use-encrypted-dns',()=>({useEncryptedDns:()=>({status:mockDnsStatus})}));
import React from 'react';
import { fireEvent, render } from '@testing-library/react-native';
import { ProtectOverview } from '@/components/ProtectOverview';
import { appI18n } from '@/i18n/runtime';
import { createDefaultRecoveryState } from '@/lib/recovery-state';
import type { ProtectionCapability } from 'freed-protection';
jest.mock('lucide-react-native', () => new Proxy({}, { get: () => () => null }));
jest.mock('@/components/MomentumCompanion', () => ({ MomentumCompanion: () => null }));
jest.mock('@/components/DirectionalIcons', () => ({ ChevronRight: () => null }));
jest.mock('@/components/EncryptedDnsSection', () => ({ EncryptedDnsSection: () => <></> }));
jest.mock('@/hooks/use-app-preferences', () => ({ useAppPreferences: () => ({ mode: 'light' }), useOptionalAppPreferences: () => null }));
jest.mock('expo-router', () => ({ Link: ({ children }: any) => children }));
const capability: ProtectionCapability = { platform: 'android', screenTime: false, managedSettings: false, accessibility: true, usageStats: true, dnsFiltering: true, localVpnFallback: true, notes: [] };
beforeEach(async () => { mockDnsStatus={supported:false,releaseEnabled:false,configured:false,enabled:false,healthy:null,reason:null,provider:'cloudflare-families',requiresSettings:false}; await appI18n.changeLanguage('en'); });
test('the two plain-language cards preserve independent setup intent', () => {
 const setup=jest.fn();
 const screen=render(<ProtectOverview capability={capability} status={null} settings={createDefaultRecoveryState().disciplineSettings} onSetup={setup} />);
 expect(setup).not.toHaveBeenCalled();
 fireEvent.press(screen.getByTestId('protect-websites-setup'));
 expect(setup).toHaveBeenLastCalledWith('websites');
 fireEvent.press(screen.getByTestId('protect-apps-setup'));
 expect(setup).toHaveBeenLastCalledWith('apps');
 expect(screen.getByTestId('protect-websites-title')).toHaveTextContent('Adult websites');
 expect(screen.getByTestId('protect-apps-title')).toHaveTextContent('Apps');
 expect(screen.getByTestId('protect-websites-setup')).toHaveTextContent('Set up');
 expect(screen.getByTestId('protect-apps-setup')).toHaveTextContent('Set up');
 expect(screen.getByTestId('protect-apps-coverage')).toHaveTextContent(/Shorts and Reels cannot be separated/);
});
test('missing native capabilities still expose reviewable website setup without claiming activation', () => {
 const setup=jest.fn();
 const screen=render(<ProtectOverview capability={null} status={null} settings={createDefaultRecoveryState().disciplineSettings} onSetup={setup} />);
 expect(screen.getByTestId('protect-websites-status')).toHaveTextContent('Unavailable');
 expect(screen.getByTestId('protect-apps-status')).toHaveTextContent('Unavailable');
 fireEvent.press(screen.getByTestId('protect-websites-setup'));
 expect(setup).toHaveBeenCalledWith('websites');
 expect(screen.getByTestId('protect-websites-setup')).toHaveTextContent('Check');
});
