test('failed breathing save retains its receipt for retry and successful retry is deduplicated', () => {
    const complete = jest.fn().mockImplementationOnce(() => { throw new Error('disk'); });
    const back = jest.fn();
    const view = render(wrap(<FunctionalBreathingScreen onBack={back} onComplete={complete} onSupport={jest.fn()}/>));
    fireEvent.press(view.getByRole('button', { name: 'Begin' }));
    advance(5000);
    fireEvent.press(view.getByRole('button', { name: 'Finish' }));
    fireEvent.press(view.getByTestId('tool-save'));
    expect(view.getByRole('alert')).toHaveTextContent(/Your session could not be saved\. The result is still here\./);
    expect(values.has(BREATHING_SESSION_KEY)).toBe(true);
    expect(back).not.toHaveBeenCalled();
    fireEvent.press(view.getByTestId('tool-save'));
    expect(complete).toHaveBeenCalledTimes(2);
    expect(complete.mock.calls[1]).toEqual(complete.mock.calls[0]);
    fireEvent.press(view.getByTestId('tool-save'));
    expect(complete).toHaveBeenCalledTimes(2);
});
test('scratch cleanup failure after durable breathing save is truthful and Continue retries only cleanup', () => {
    const complete = jest.fn(), back = jest.fn();
    const view = render(wrap(<FunctionalBreathingScreen onBack={back} onComplete={complete} onSupport={jest.fn()}/>));
    fireEvent.press(view.getByRole('button', { name: 'Begin' }));
    advance(5000);
    fireEvent.press(view.getByRole('button', { name: 'Finish' }));
    clearFails = true;
    fireEvent.press(view.getByTestId('tool-save'));
    expect(complete).toHaveBeenCalledTimes(1);
    expect(view.getByRole('alert')).toHaveTextContent(/Session saved\. Resume-state cleanup could not finish\./);
    expect(view.getByRole('button', { name: 'Continue' })).toBeOnTheScreen();
    expect(view.queryByRole('button', { name: 'Leave without recording' })).toBeNull();
    expect(back).not.toHaveBeenCalled();
    expect(values.has(BREATHING_SESSION_KEY)).toBe(true);
    clearFails = false;
    fireEvent.press(view.getByRole('button', { name: 'Continue' }));
    expect(complete).toHaveBeenCalledTimes(1);
    expect(back).toHaveBeenCalledTimes(1);
    expect(values.has(BREATHING_SESSION_KEY)).toBe(false);
});
test('a reopened midnight Journal draft requires explicit transfer and saves the same note under today', () => {
    const save = jest.fn();
    const words = 'My private unfinished words';
    const first = render(wrap(<JournalScreen record={null} onSave={save} onBack={jest.fn()}/>));
    fireEvent.changeText(first.getByTestId('journal-reflection'), words);
    first.unmount();
    jest.setSystemTime(new Date(2026, 9, 4, 8, 0, 0));
    const view = render(wrap(<JournalScreen record={null} onSave={save} onBack={jest.fn()}/>));
    expect(view.getByTestId('journal-reflection')).toHaveProp('value', words);
    expect(view.getByTestId('journal-save')).toBeDisabled();
    expect(view.getByRole('alert')).toHaveTextContent(/A new day has started/);
    fireEvent.press(view.getByTestId('journal-save'));
    expect(save).not.toHaveBeenCalled();
    fireEvent.press(view.getByRole('button', { name: 'Use draft today' }));
    expect(view.getByTestId('journal-reflection')).toHaveProp('value', words);
    expect(view.getByTestId('journal-save')).not.toBeDisabled();
    fireEvent.press(view.getByTestId('journal-save'));
    expect(save).toHaveBeenCalledTimes(1);
    expect(save).toHaveBeenCalledWith(words, '2026-10-04');
});

test('a saved breathing receipt restores cleanup-only controls after restart', () => {
  const ids: string[] = []; const complete = jest.fn((input: { sessionId: string }) => { ids.push(input.sessionId); });
  const first = render(wrap(<FunctionalBreathingScreen completedSessionIds={ids} onBack={jest.fn()} onComplete={complete} onSupport={jest.fn()} />));
  fireEvent.press(first.getByRole('button', { name: 'Begin' })); advance(5000); fireEvent.press(first.getByRole('button', { name: 'Finish' }));
  clearFails = true; fireEvent.press(first.getByTestId('tool-save')); first.unmount();
  const back = jest.fn(); const restored = render(wrap(<FunctionalBreathingScreen completedSessionIds={[...ids]} onBack={back} onComplete={complete} onSupport={jest.fn()} />));
  expect(restored.getByRole('header', { name: 'Session saved' })).toBeOnTheScreen();
  expect(restored.queryByRole('button', { name: 'Begin' })).toBeNull();
  expect(restored.queryByRole('button', { name: 'Leave without recording' })).toBeNull();
  expect(restored.getByTestId('tool-record-practice')).toBeDisabled();
  expect(restored.getByTestId('tool-outcome-helped')).toBeDisabled();
  clearFails = false; fireEvent.press(restored.getByRole('button', { name: 'Continue' }));
  expect(complete).toHaveBeenCalledTimes(1); expect(back).toHaveBeenCalledTimes(1);
  expect(values.has(BREATHING_SESSION_KEY)).toBe(false);
});
