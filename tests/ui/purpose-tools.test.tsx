test('Journal restores exact authored words after navigation and retries a failed save without inventing check-in answers', () => {
    const words = '  Back\n私の言葉 — my private note  ';
    const save = jest.fn().mockImplementationOnce(() => { throw new Error('full disk'); });
    const back = jest.fn();
    const first = render(wrap(<JournalScreen record={null} onSave={save} onBack={back}/>));
    fireEvent.changeText(first.getByTestId('journal-reflection'), words);
    first.unmount();
    const view = render(wrap(<JournalScreen record={null} onSave={save} onBack={back}/>));
    expect(view.getByTestId('journal-reflection')).toHaveProp('value', words);
    fireEvent.press(view.getByTestId('journal-save'));
    expect(view.getByRole('alert')).toHaveTextContent(/This entry could not be saved\. Your changes are still here\./);
    expect(view.getByTestId('journal-reflection')).toHaveProp('value', words);
    expect(back).not.toHaveBeenCalled();
    expect(values.has(RECOVERY_DRAFT_STORAGE_KEYS.journal)).toBe(true);
    fireEvent.press(view.getByTestId('journal-save'));
    expect(save).toHaveBeenNthCalledWith(1, words, '2026-10-03');
    expect(save).toHaveBeenNthCalledWith(2, words, '2026-10-03');
    expect(back).toHaveBeenCalledTimes(1);
    expect(values.has(RECOVERY_DRAFT_STORAGE_KEYS.journal)).toBe(false);
});
