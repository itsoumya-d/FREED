import assert from 'node:assert/strict';
import { createAccountOperationGate } from '../src/lib/account-operation';
let scope: string | null = 'account-a';
const gate = createAccountOperationGate(() => scope);
const purchase = gate.begin();
assert.equal(purchase.isCurrent(), true);
scope = null;
assert.equal(purchase.isCurrent(), false);
assert.throws(() => purchase.assertCurrent(), /account changed/);
scope = 'account-a'; gate.invalidate();
assert.equal(purchase.isCurrent(), false);
const backup = gate.begin(); scope = 'account-b';
assert.equal(backup.isCurrent(), false);
assert.equal(backup.bindCreatedGuest(true), false);
scope = null;
const guest = gate.begin(); scope = 'guest-new';
assert.equal(guest.bindCreatedGuest(true), true);
scope = 'guest-other';
assert.equal(guest.bindCreatedGuest(true), false);
scope = null; const switched = gate.begin(); scope = 'permanent-b';
assert.equal(switched.bindCreatedGuest(false), false);
scope = null; const cancelled = gate.begin(); cancelled.cancel(); scope = 'guest-third';
assert.equal(cancelled.bindCreatedGuest(true), false);
console.log('PASS: async account ownership, guest binding, sign-out and cancellation');
