import assert from "node:assert/strict";
import * as premium from "../src/lib/premium-entitlement";
const now = Date.parse("2026-10-03T10:00:00.000Z");
const proof = { productId: "freed_premium_yearly", platform: "ios", status: "verified", verifiedAt: new Date(now).toISOString(), expiresAt: new Date(now + 3600000).toISOString(), ownerUid: "owner_a" };
assert.equal(typeof premium.getMembershipSummary, "function", "Membership presentation needs a typed verified-evidence summary.");
const active = premium.getMembershipSummary(proof, now, "owner_a");
assert.equal(active.state, "active");
assert.equal(active.planId, "yearly");
assert.equal(active.accessThrough, proof.expiresAt);
assert.equal(active.renewal, "unknown", "Access expiry does not prove automatic renewal, cancellation, or next billing.");
assert.equal(active.renewsAt, null);
assert.equal(premium.getMembershipSummary(proof, now + 3600000, "owner_a").state, "expired");
const stale = premium.getMembershipSummary({ ...proof, expiresAt: new Date(now + 2 * premium.PREMIUM_OFFLINE_TTL_MS).toISOString() }, now + premium.PREMIUM_OFFLINE_TTL_MS, "owner_a");
assert.equal(stale.state, "verification-required");
assert.equal(stale.accessThrough, null, "Stale evidence cannot promise future access.");
assert.equal(premium.getMembershipSummary({ ...proof, status: "revoked" }, now, "owner_a").state, "revoked");
assert.equal(premium.getMembershipSummary({ ...proof, status: "inactive" }, now, "owner_a").state, "inactive");
assert.deepEqual(premium.getMembershipSummary(proof, now, "other"), premium.getMembershipSummary(null, now, "other"), "A different account's billing history must not leak into the summary.");
assert.equal(premium.getMembershipSummary({ ...proof, verifiedAt: new Date(now + 3600000).toISOString() }, now, "owner_a").accessThrough, null);
const lifetime = premium.getMembershipSummary({ ...proof, productId: "freed_premium_lifetime", expiresAt: null }, now, "owner_a");
assert.equal(lifetime.renewal, "not-applicable");
assert.equal(lifetime.accessThrough, null);
console.log("Verified membership summary tests passed");
