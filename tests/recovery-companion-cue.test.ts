import assert from 'node:assert/strict';
import { createDefaultRecoveryState, recordDailyCheckIn, recordDailyPledge, recordDailyHabitCompletion } from '../src/lib/recovery-state';
import { getRecoveryCompanionCue } from '../src/lib/recovery-companion-cue';
const state = createDefaultRecoveryState();
const at = new Date(2026, 9, 3, 12);
assert.equal(getRecoveryCompanionCue(null, state), undefined, 'hydration never invents an event');
assert.equal(getRecoveryCompanionCue(state, { ...state, signedInEmail: 'private@example.com' }), undefined);
const pledge = recordDailyPledge(state, at);
assert.equal(getRecoveryCompanionCue(state, pledge)?.pose, 'saved');
assert.equal(getRecoveryCompanionCue(pledge, pledge), undefined);
const practice = recordDailyHabitCompletion(state, { key: 'exercise', label: 'Exercise', completed: true }, at.toISOString());
assert.equal(getRecoveryCompanionCue(state, practice)?.pose, 'saved');
const checkin = recordDailyCheckIn(state, { mood: 'steady', urgeLevel: 2, sleepQuality: 3, reflection: 'private secret never enters cue' }, at.toISOString());
const cue = getRecoveryCompanionCue(state, checkin);
assert.ok(cue);
assert.ok(['saved', 'celebrate'].includes(cue.pose));
assert.ok(!JSON.stringify(cue).includes('private'));
assert.equal(getRecoveryCompanionCue(checkin, checkin), undefined);
console.log('Committed-record cues, hydration suppression, deduplication and privacy checks passed.');
