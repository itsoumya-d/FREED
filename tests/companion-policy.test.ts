import assert from 'node:assert/strict';
import { companionMayAnimate, createCompanionCueRegistry, resolveCompanionPose, companionSceneFamily } from '../src/lib/companion-policy';
const active = { visible: true, focused: true, foreground: true, reduceMotion: false, motionEnabled: true };
assert.equal(companionMayAnimate(active), true);
for (const gate of ['visible', 'focused', 'foreground', 'motionEnabled'] as const)
    assert.equal(companionMayAnimate({ ...active, [gate]: false }), false, gate);
assert.equal(companionMayAnimate({ ...active, reduceMotion: true }), false);
assert.equal(resolveCompanionPose(undefined, 'calm'), 'breathe');
assert.equal(resolveCompanionPose('repair', 'celebrate'), 'repair');
assert.equal(companionSceneFamily('shield'), 'protection');
assert.equal(companionSceneFamily('write', 'reflection'), 'reflection');
let saved: string | null = null;
const storage = { getItem: () => saved, setItem: (_key: string, value: string) => { saved = value; } };
const registry = createCompanionCueRegistry(storage, 3);
assert.equal(registry.consume({ id: 'save/day1', pose: 'saved', earned: true }, false), false);
assert.equal(registry.consume({ id: 'save/day1', pose: 'saved', earned: true }, true), true);
assert.equal(registry.consume({ id: 'save/day1', pose: 'saved', earned: true }, true), false);
assert.equal(createCompanionCueRegistry(storage, 3).consume({ id: 'save/day1', pose: 'saved', earned: true }, true), false, 'earned receipt survives remount/restart');
assert.equal(registry.consume({ id: '', pose: 'celebrate' }, true), false);
for (const id of ['a', 'b', 'c', 'd'])
    registry.consume({ id, pose: 'guide' }, true);
assert.ok(registry.size() <= 3, 'transient registry is bounded');
assert.equal(registry.consume({ id: 'd', pose: 'guide' }, true), false);
const failed = createCompanionCueRegistry({ getItem: () => '{broken', setItem: () => { throw Error('disk'); } });
assert.equal(failed.consume({ id: 'saved1', pose: 'saved', earned: true }, true), true);
assert.equal(failed.consume({ id: 'saved1', pose: 'saved', earned: true }, true), false, 'storage failure still prevents replay during this process');
const defaultEarned = createCompanionCueRegistry(storage, 3);
assert.equal(defaultEarned.consume({ id: 'save/no-earned-flag', pose: 'saved' }, true), true);
assert.equal(createCompanionCueRegistry(storage, 3).consume({ id: 'save/no-earned-flag', pose: 'saved' }, true), false, 'saved cue persists even without an optional earned flag');
registry.clear();
assert.equal(registry.size(),0,'explicit deletion clears transient receipts');
assert.equal(createCompanionCueRegistry(storage).consume({id:'save/day1',pose:'saved',earned:false},true),true,'explicit deletion removes persisted receipt history');
assert.equal(registry.consume({id:'d',pose:'guide'},true),true,'transient receipts can be used after explicit deletion');
assert.equal(registry.consume({id:'save/day1',pose:'saved'},true),true,'earned receipts can be used after explicit deletion');
const eraseFailure=createCompanionCueRegistry({getItem:()=>null,setItem:()=>{throw Error('disk');}});
assert.equal(eraseFailure.consume({id:'keep-on-failed-delete',pose:'saved'},true),true);
assert.throws(()=>eraseFailure.clear(),/disk/,'deletion failures remain observable');
assert.equal(eraseFailure.consume({id:'keep-on-failed-delete',pose:'saved'},true),false,'failed deletion retains in-process deduplication');
console.log('Companion lifecycle and cue policy passed');
